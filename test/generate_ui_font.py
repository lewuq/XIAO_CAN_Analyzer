"""Generate the analyzer's native-size Montserrat Bold glyphs."""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


# Pixel size, cell height, and baseline for labels, headings, and counters.
SIZES = ((9, 8, 7), (16, 15, 12), (26, 22, 19))
RASTER_WIDTH = 40


def render_glyph(font, char, height, baseline, max_width):
    canvas = Image.new("1", (RASTER_WIDTH, 3 * height))
    draw = ImageDraw.Draw(canvas)
    # Use FreeType's monochrome grid fitting at the real panel resolution.
    draw.fontmode = "1"
    draw.text((4, height + baseline), char, font=font, fill=1, anchor="ls")
    bounds = canvas.getbbox()
    if bounds is None:
        return 0, []

    glyph = canvas.crop(bounds)
    # Fit complete ink bounds into the OLED cell. This preserves cap strokes
    # and also leaves room for descenders and punctuation at small sizes.
    width = min(glyph.width, max_width)
    fitted_height = min(glyph.height, height)
    if glyph.size != (width, fitted_height):
        glyph = glyph.resize((width, fitted_height), Image.Resampling.NEAREST)
    top = min(max(0, bounds[1] - height), height - glyph.height)
    packed = [0] * ((width * height + 7) // 8)
    for row in range(glyph.height):
        for column in range(width):
            # Each byte holds eight consecutive pixels, least significant bit first.
            index = (top + row) * width + column
            if glyph.getpixel((column, row)):
                packed[index // 8] |= 1 << (index % 8)
    return width, packed


def generate(font_path, output):
    lines = [
        "/* Generated by test/generate_ui_font.py from Montserrat Bold.",
        " * Copyright 2011 The Montserrat Project Authors.",
        " * Font data licensed under the SIL Open Font License 1.1.",
        " * See docs/fonts/OFL-Montserrat.txt.",
        " */",
        "",
    ]
    for size, (nominal, height, baseline) in enumerate(SIZES, start=1):
        font = ImageFont.truetype(font_path, nominal)
        if font.getname() != ("Montserrat", "Bold"):
            raise ValueError("Expected a static Montserrat Bold font")
        data, glyphs = [], []
        for code in range(32, 127):
            char = chr(code)
            # Small hex offsets must fit the same six-pixel cell as digits.
            width, packed = render_glyph(font, char, height, baseline, 6 if size == 1 else RASTER_WIDTH)
            advance = width + 1 if width else max(1, round(font.getlength(char)))
            glyphs.append(f"    {{{len(data)}, {width}, {advance}}}, /* U+{code:04X} */")
            data.extend(packed)

        lines.append(f"static const struct glyph glyphs_{size}[] = {{")
        lines.extend(glyphs)
        lines.extend(("};", "", f"static const uint8_t pixels_{size}[] = {{"))
        for start in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{value:02x}" for value in data[start:start + 16]) + ",")
        lines.extend(("};", ""))

    lines.extend((
        "static const struct bitmap_font fonts[] = {",
        *(f"    {{glyphs_{i}, pixels_{i}, {height}}},"
          for i, (_, height, _) in enumerate(SIZES, start=1)),
        "};",
        "",
    ))
    output.write_text("\n".join(lines), encoding="ascii")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path, help="Montserrat-Bold.ttf")
    parser.add_argument("output", type=Path, nargs="?", default=Path("src/ui_font.h"))
    args = parser.parse_args()
    generate(args.font, args.output)
